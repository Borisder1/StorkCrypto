/**
 * 6-step fallback algorithm as specified in Section 7 of the specification:
 * 1. Verified video in selected language
 * 2. Verified video with subtitleLanguages containing selected language
 * 3. Verified English official video
 * 4. Official article in selected language
 * 5. English official article
 * 6. Controlled unavailable state
 */
export function resolveLessonVariant(
    lesson: AcademyLesson,
    preferredLang: AcademyLanguage
): { variant: AcademyVariant; isFallback: boolean; fallbackReason?: string } {
    const directVariant = lesson.variants[preferredLang];

    // 1. Direct verified video in selected language
    if (directVariant?.videoId && directVariant.spokenLanguage === preferredLang && directVariant.validationStatus === 'verified') {
        return { variant: directVariant, isFallback: false };
    }

    // 2. Direct verified video with subtitles in selected language
    if (directVariant?.videoId && directVariant.subtitleLanguages?.includes(preferredLang) && directVariant.validationStatus === 'verified') {
        return { variant: directVariant, isFallback: false };
    }

    // 3. Verified English official video
    const enVariant = lesson.variants['en'];
    if (enVariant?.videoId && enVariant.validationStatus === 'verified') {
        const langName = preferredLang === 'uk' ? 'українське' : preferredLang === 'ru' ? 'російське' : 'обраною мовою';
        return {
            variant: directVariant || enVariant,
            isFallback: preferredLang !== 'en',
            fallbackReason: preferredLang !== 'en'
                ? `Показано English official lesson, оскільки ${langName} відео недоступне.`
                : undefined
        };
    }

    // 4. Official article in selected language
    if (directVariant?.officialArticleUrl) {
        return {
            variant: directVariant,
            isFallback: false
        };
    }

    // 5. English official article
    if (enVariant?.officialArticleUrl) {
        return {
            variant: enVariant,
            isFallback: preferredLang !== 'en',
            fallbackReason: preferredLang !== 'en'
                ? `Показано English official article, оскільки версія для ${preferredLang} відсутня.`
                : undefined
        };
    }

    // 6. Controlled unavailable state (fallback to whatever exists or minimal safe stub)
    const fallback = directVariant || enVariant || Object.values(lesson.variants)[0]!;
    return {
        variant: fallback,
        isFallback: true,
        fallbackReason: 'Контент тимчасово недоступний для обраного регіону.'
    };
}
